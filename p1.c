#include <stdio.h>
int main()// Arithmetic Operations Practical
{
    int a=100;
    int b=60;
    
    printf("The Sum of two numbers is %d\n", a+b);
    printf("The Subtraction of two numbers is %d\n", a-b);
    printf("The Multiplication of two numbers is %d\n", a*b);
    printf("The Division of two numbers is %d\n", a/b);
    printf("The Modulous of two numbers is %d\n", a%b);
    return 0;
}
